	void FillCardSearchMetadata(std::vector<qm_card_registry::SCardDefault> &vCards)
	{
		for(auto &Card : vCards)
		{
			for(const auto &Metadata : s_aCards)
			{
				if(str_comp(Card.m_pStableId, Metadata.m_pStableId) != 0)
					continue;
				Card.m_pSettings = Metadata.m_pSettings;
				Card.m_SettingCount = Metadata.m_Count;
				break;
			}
		}
	}
